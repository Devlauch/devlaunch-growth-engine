/**
 * Pluggable file storage for lead-magnet uploads (Milestone 3) — closes the
 * gap 265_create_lead_magnets.sql's own comment documents: `file_url` was a
 * client-supplied-URL stub with no real upload/storage infra at all.
 *
 * No cloud object-storage account (S3 or equivalent) is available in this
 * environment (checked docker-compose.yml / env.ts — there isn't one),
 * exactly the same situation PDF reports were already in (see
 * apps/worker/src/reports/reportFileStore.ts and docker-compose.yml's
 * `report_files` volume). This follows that EXACT established convention
 * rather than inventing a new one: local-disk storage, behind a pluggable
 * `FileStorage` interface so a real cloud backend is a drop-in swap once a
 * real account/credentials exist, on its own dedicated
 * `lead_magnet_files` volume (kept separate from `report_files` — different
 * feature, different lifecycle/retention expectations).
 */
import { createHash, randomUUID } from "node:crypto";
import { mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { env } from "../config/env.js";
import { buildSignedDownload } from "./signedDownloadUrl.js";

export interface FileStorageUploadResult {
  /** Opaque storage key — persisted (e.g. in lead_magnets.storage_key), passed back into getSignedDownloadUrl/delete. */
  key: string;
  /** A reference URL/path for this file. For LocalDiskFileStorage, a signed, time-limited path (see getSignedDownloadUrl). */
  url: string;
}

export interface FileStorage {
  upload(buffer: Buffer, filename: string, contentType: string): Promise<FileStorageUploadResult>;
  getSignedDownloadUrl(key: string, expirySeconds: number): Promise<string>;
  delete(key: string): Promise<void>;
}

/** Keeps only safe characters from a client-supplied filename for use in a path segment / Content-Disposition. */
function sanitizeFilename(filename: string): string {
  const base = path.basename(filename).replace(/[^a-zA-Z0-9._-]/g, "_");
  return base.length > 0 ? base.slice(0, 180) : "file";
}

/**
 * Real, working default implementation: writes to a local-disk directory
 * (env.leadMagnetFilesDir, mounted as a dedicated Docker volume in
 * production — see docker-compose.yml's `lead_magnet_files` volume),
 * exactly mirroring reportFileStore.ts's shape (mkdir -p, then writeFile).
 *
 * Storage keys are `<sha256-of-random-uuid-prefix>/<sanitized-filename>` —
 * namespaced into a subdirectory per upload so two uploads with the same
 * original filename never collide and never overwrite each other.
 *
 * `getSignedDownloadUrl` does not itself serve the file (this class has no
 * knowledge of Express/routing) — it returns a relative API path
 * (`/api/v1/public/lead-magnet-downloads/<key>?expires=...&sig=...`) that
 * routes/leadMagnetUploads.ts's public download route is responsible for
 * mounting and verifying (see signedDownloadUrl.ts for the HMAC scheme).
 */
export class LocalDiskFileStorage implements FileStorage {
  constructor(private readonly baseDir: string = env.leadMagnetFilesDir) {}

  private fullPath(key: string): string {
    // key is always ONLY ever generated by this class (randomUUID + a
    // sanitized filename, never attacker-controlled path segments), so this
    // never resolves outside baseDir.
    return path.join(this.baseDir, key);
  }

  async upload(buffer: Buffer, filename: string, _contentType: string): Promise<FileStorageUploadResult> {
    const prefix = createHash("sha256").update(randomUUID()).digest("hex").slice(0, 16);
    const key = path.posix.join(prefix, sanitizeFilename(filename));
    const fullPath = this.fullPath(key);
    await mkdir(path.dirname(fullPath), { recursive: true });
    await writeFile(fullPath, buffer);
    const url = await this.getSignedDownloadUrl(key, 3600);
    return { key, url };
  }

  async getSignedDownloadUrl(key: string, expirySeconds: number): Promise<string> {
    const { expires, sig } = buildSignedDownload(key, expirySeconds);
    return `/api/v1/public/lead-magnet-downloads/${encodeURIComponent(key)}?expires=${expires}&sig=${sig}`;
  }

  async delete(key: string): Promise<void> {
    await rm(this.fullPath(key), { force: true });
  }

  /** Used only by the download route to stream real bytes back — not part of the FileStorage interface contract. */
  async readFile(key: string): Promise<Buffer> {
    return readFile(this.fullPath(key));
  }

  async fileSize(key: string): Promise<number> {
    const s = await stat(this.fullPath(key));
    return s.size;
  }
}

export class NotConfiguredError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "NotConfiguredError";
  }
}

/**
 * Documented swap-in path for a real cloud object-storage backend (S3 or
 * equivalent), once a real account/credentials exist in this environment.
 * Deliberately NOT half-implemented against no credentials (that would risk
 * exactly the kind of fabricated-integration this codebase's
 * `NotConfigured*` convention exists to avoid — see
 * decisionMakerProvider.ts/bookingProvider.ts) — every method throws,
 * honestly, rather than silently no-op'ing or faking a successful upload.
 *
 * To implement for real:
 *   - upload(): PutObjectCommand (AWS SDK v3's @aws-sdk/client-s3, or an
 *     S3-compatible client for R2/Spaces/MinIO/GCS-via-S3-interop) with the
 *     buffer, a generated key, and ContentType; the bucket name/region/
 *     endpoint/credentials would come from new env.ts fields following the
 *     same `?? null` optional convention as integrationCredentialsKey.
 *   - getSignedDownloadUrl(): @aws-sdk/s3-request-presigner's
 *     getSignedUrl(GetObjectCommand) with Expires: expirySeconds — a real
 *     cloud-native signed URL, not the HMAC scheme LocalDiskFileStorage
 *     uses (that scheme exists only because local disk has no native
 *     signed-URL concept).
 *   - delete(): DeleteObjectCommand.
 * None of this can be tested against a real bucket without a real cloud
 * account — this class exists so the *interface* is implemented and ready,
 * not to pretend an untested S3 call path is production-ready.
 */
export class NotConfiguredS3FileStorage implements FileStorage {
  async upload(_buffer: Buffer, _filename: string, _contentType: string): Promise<FileStorageUploadResult> {
    throw new NotConfiguredError(
      "S3 (or equivalent cloud object storage) is not configured in this environment — no bucket/credentials " +
        "exist. Implement FileStorage against a real S3 SDK client and env-var-driven bucket/region/credentials " +
        "once a real cloud account is available; see this class's doc comment for the exact AWS SDK v3 calls.",
    );
  }

  async getSignedDownloadUrl(_key: string, _expirySeconds: number): Promise<string> {
    throw new NotConfiguredError("S3 is not configured in this environment — see NotConfiguredS3FileStorage's doc comment.");
  }

  async delete(_key: string): Promise<void> {
    throw new NotConfiguredError("S3 is not configured in this environment — see NotConfiguredS3FileStorage's doc comment.");
  }
}

/** The FileStorage backend used in production. Swap for NotConfiguredS3FileStorage's real implementation once credentials exist. */
export function buildFileStorage(): FileStorage {
  return new LocalDiskFileStorage();
}
