import { z } from "zod";
import type { AgentDefinition } from "../core/agentRunner.js";
import { registerTool, assignAgentTools, type AgentTool } from "../core/agentTools.js";
import { computeFunnelDropoff, type FunnelDropoffResult } from "../../funnelDropoff.js";
import { generateExperimentSuggestions, type ExperimentSuggestion } from "../../experimentSuggestions.js";
import { requireProjectId, type QueryableDb } from "./types.js";

/**
 * landingPageOptimizationAgent: grounds its output in ONE real landing_pages
 * row plus its real landing_page_events counts (263/266_create_landing_pages*.sql
 * — the same page_view/form_submit counts growthAdvisor.ts's
 * weakLandingPageConversionRule reads) and the project's real funnel
 * drop-off (funnelDropoff.ts's computeFunnelDropoff, reused directly).
 * Experiment suggestions are generated by experimentSuggestions.ts's real
 * rule-based generateExperimentSuggestions() from that real drop-off data
 * (landing-page-finding-driven suggestions are omitted here since this
 * agent deliberately does not perform a live crawl of the page — see
 * landingPageAudit.ts's own header on why a live fetch is out of scope for
 * a read-only grounding tool).
 */

export interface LandingPageOptimizationEvidence {
  landingPage: Record<string, unknown> | null;
  pageViewCount: number;
  formSubmitCount: number;
  conversionRate: number | null;
  funnelDropoff: FunnelDropoffResult;
  experimentSuggestions: ExperimentSuggestion[];
}

export async function gatherLandingPageOptimizationEvidence(
  tenantDb: QueryableDb,
  tenantId: string,
  projectId: string,
  subjectId: string,
): Promise<LandingPageOptimizationEvidence> {
  const pageResult = await tenantDb.query(
    `SELECT id, slug, title, audience_label, headline, status, cta_text, cta_url, custom_domain, created_at
       FROM landing_pages
      WHERE id = $1 AND tenant_id = $2 AND project_id = $3`,
    [subjectId, tenantId, projectId],
  );
  const landingPage = pageResult.rows[0] ?? null;

  let pageViewCount = 0;
  let formSubmitCount = 0;
  if (landingPage) {
    const eventsResult = await tenantDb.query<{ views: string; submits: string }>(
      `SELECT count(*) FILTER (WHERE event_type = 'page_view') AS views,
              count(*) FILTER (WHERE event_type = 'form_submit') AS submits
         FROM landing_page_events
        WHERE tenant_id = $1 AND landing_page_id = $2`,
      [tenantId, subjectId],
    );
    pageViewCount = Number(eventsResult.rows[0]?.views ?? 0);
    formSubmitCount = Number(eventsResult.rows[0]?.submits ?? 0);
  }

  const funnelDropoff = await computeFunnelDropoff(tenantDb, tenantId, projectId);
  const experimentSuggestions = generateExperimentSuggestions([], funnelDropoff);

  return {
    landingPage,
    pageViewCount,
    formSubmitCount,
    conversionRate: pageViewCount > 0 ? formSubmitCount / pageViewCount : null,
    funnelDropoff,
    experimentSuggestions,
  };
}

const landingPageOptimizationEvidenceTool: AgentTool<{ landingPageId: string }, LandingPageOptimizationEvidence> = {
  name: "landing_page_optimization_evidence_read",
  description:
    "Reads one real landing page's record, its real page_view/form_submit counts (landing_page_events), the project's real funnel drop-off, and rule-based experiment suggestions derived from that real drop-off. Read-only.",
  inputSchema: z.object({ landingPageId: z.string().uuid() }),
  async execute(input, context) {
    const projectId = requireProjectId(context);
    return gatherLandingPageOptimizationEvidence(context.tenantDb, context.tenantId, projectId, input.landingPageId);
  },
};

registerTool(landingPageOptimizationEvidenceTool);

const outputSchema = z.object({
  summary: z.string().min(1),
  findings: z.array(z.string()),
  recommendedExperiments: z.array(z.object({ name: z.string(), hypothesis: z.string() })),
  evidence: z.array(z.string()),
});

export type LandingPageOptimizationOutput = z.infer<typeof outputSchema>;

export const landingPageOptimizationAgent: AgentDefinition<{ landingPageId: string }, LandingPageOptimizationOutput> = {
  key: "landing_page_optimization",
  label: "Landing Page Optimization Agent",
  description:
    "Analyzes one real landing page's conversion performance and recommends experiments, grounded only in its real page_view/form_submit counts and the project's real funnel drop-off.",
  systemPrompt:
    "You are a landing page optimization assistant for a B2B marketing platform. You will be given a real landing page record, its real pageViewCount/formSubmitCount/conversionRate (from landing_page_events), the project's real funnel drop-off stages, and rule-based experiment suggestions already generated from that real data. You never invent a conversion rate, a visitor count, or an experiment idea beyond what is given. If pageViewCount is 0, say there is not enough traffic data to evaluate this page rather than guessing. When recommending an experiment, only restate/select from the given experimentSuggestions — do not invent new ones not present in the evidence.",
  inputSchema: z.object({ landingPageId: z.string().uuid() }),
  outputSchema,
  outputFormatDescription:
    '{ "summary": string, "findings": string[] (grounded in the real counts/drop-off given), "recommendedExperiments": {name: string, hypothesis: string}[] (drawn only from the given experimentSuggestions), "evidence": string[] }',
  tools: [landingPageOptimizationEvidenceTool],
  requiresApproval: false,
  maxTokens: 700,
};

assignAgentTools(landingPageOptimizationAgent.key, [landingPageOptimizationEvidenceTool.name]);
